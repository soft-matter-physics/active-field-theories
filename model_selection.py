ETA   = 1.0   # shear viscosity      (AN)
GAMMA = 1.0   # rotational viscosity (AN)

AMH_CFG = dict(Ng=32, Nt=4000, dt=0.005, h=1.0, Nf=100)
AN_CFG  = dict(Ng=32, Nt=4000, dt=0.005, h=1.0, Nf=100)

N_FRAMES_AMH = 100    # frames used to build the AMH network's input image
N_FRAMES_AN  = 100   # frames used to build the AN  network's input image

EPS = 1e-16          # regularizer inside log10(E + EPS), matches Algorithm 1


def configure_system(Ng, Nt=4000, dt=0.005, h=1.0, Nf=100,
                     n_frames_amh=None, n_frames_an=None):
    """Configure grid/snapshot dimensions before loading matching networks."""
    global N_FRAMES_AMH, N_FRAMES_AN
    config = dict(Ng=int(Ng), Nt=int(Nt), dt=float(dt), h=float(h), Nf=int(Nf))
    AMH_CFG.update(config)
    AN_CFG.update(config)
    N_FRAMES_AMH = int(Nf if n_frames_amh is None else n_frames_amh)
    N_FRAMES_AN = int(Nf if n_frames_an is None else n_frames_an)

# Sign convention: both k_tilde (AMH) and zeta (AN) are sampled/trained as
# always-negative quantities but the networks predict log10(|value|).
# We restore the sign here before feeding a value back into the simulator.


