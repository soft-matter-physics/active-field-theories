"""
AMH vs AN Model Selection
=========================
Classify an *unknown* velocity field (vx, vy) as having been generated by 
Active Model H (AMH) or Active Nematics (AN).

Everything needed is in this one file:
    - both simulators (copied from amh.py / an.py, unchanged)
    - both trained-network architectures + their native feature extractors

    - a single energy spectrum extractor used only for computing the
      resimulation discrepancy d_c
    - the full selection pipeline: predict params -> resimulate -> score ->
      Boltzmann confidence -> pick winner

PARAMETERS IN THE OUTPUT
-------------------------
Alongside the AMH/AN decision, confidence, and discrepancy scores, the
predicted nuisance parameters for both candidates (k_tilde, b, kappa_p for
AMH; kappa, zeta for AN) are included in the returned result and in the
printed summary for the winning model.

USAGE
-----
    load_models(amh_model_path, amh_scaler_path, an_model_path, an_scaler_path)
    result = classify_velocity_field(vx, vy)   # vx, vy: (Nf, Ng, Ng) arrays
"""

